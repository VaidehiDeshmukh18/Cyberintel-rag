"""Eval Report — render the latest Phase 8/9 evaluation markdown.

Reads data/eval/latest.md (produced by scripts/eval.py) and renders
it. Exposes a "rerun eval" button that regenerates the report in <10s
(retrieval-only, no LLM calls).

Design notes:
  * Pure render — no logic. The report file is the single source
    of truth; this page just shows it.
  * The rerun button shells out to the same CLI we use from the
    terminal. Keeps "live demo" and "reproducible from command line"
    aligned.
  * CSV download button for reviewers who want to sort in Excel.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import streamlit as st


LATEST_MD = Path("data/eval/latest.md")
EVAL_DIR = Path("data/eval")


def _latest_csv() -> Path | None:
    """Find the most recent results-*.csv file."""
    csvs = sorted(EVAL_DIR.glob("results-*.csv"), reverse=True)
    return csvs[0] if csvs else None


def _rerun_eval() -> tuple[bool, str]:
    """Shell out to scripts/eval.py --skip-generation. Return (ok, log)."""
    try:
        result = subprocess.run(
            [sys.executable, "scripts/eval.py", "--skip-generation"],
            capture_output=True,
            text=True,
            timeout=600,
        )
        if result.returncode != 0:
            return False, result.stderr[-2000:]
        return True, result.stdout[-2000:]
    except subprocess.TimeoutExpired:
        return False, "Eval timed out after 10 minutes."
    except Exception as e:
        return False, str(e)


def render() -> None:
    st.header("📊 Eval Report")
    st.caption(
        "Latest retrieval evaluation across all four retrievers. "
        "Generated by `scripts/eval.py`; rerun below to regenerate."
    )

    # --- Toolbar -----------------------------------------------
    col1, col2, col3 = st.columns([2, 2, 3])
    with col1:
        if st.button("🔄 Rerun eval (retrieval-only, ~10s)", type="primary"):
            with st.spinner("Running benchmark..."):
                ok, log = _rerun_eval()
            if ok:
                st.success("Eval complete. Report regenerated.")
                st.cache_data.clear()
            else:
                st.error("Eval failed.")
                st.code(log)

    with col2:
        csv_path = _latest_csv()
        if csv_path and csv_path.exists():
            with csv_path.open("rb") as f:
                st.download_button(
                    label=f"⬇️ Download CSV ({csv_path.name})",
                    data=f.read(),
                    file_name=csv_path.name,
                    mime="text/csv",
                )

    with col3:
        if LATEST_MD.exists():
            st.caption(
                f"Report file: `{LATEST_MD}` · "
                f"size: {LATEST_MD.stat().st_size:,} bytes"
            )

    st.divider()

    # --- The report itself -------------------------------------
    if not LATEST_MD.exists():
        st.warning(
            "No eval report found. Run `python scripts/eval.py --skip-generation` "
            "or click the button above."
        )
        return

    st.markdown(LATEST_MD.read_text())